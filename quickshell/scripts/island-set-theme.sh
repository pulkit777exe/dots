#!/usr/bin/env bash
# Applies a theme by name: validates it, persists the selection, and
# regenerates hyprlock's color file. This is the ONLY writer of theme state --
# Theme.qml calls this script rather than writing files itself, so there is
# one code path for "what does changing the theme actually do."
#
# Usage: island-set-theme.sh <theme-name>
set -euo pipefail

ISLAND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
THEMES_DIR="$ISLAND_DIR/themes"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/island"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/island"
STATE_FILE="$STATE_DIR/theme.json"
HYPRLOCK_COLORS="$CACHE_DIR/hyprlock-colors.conf"

theme_name="${1:?usage: island-set-theme.sh <theme-name>}"
theme_file="$THEMES_DIR/$theme_name.json"

if [[ ! -f "$theme_file" ]]; then
    echo "island: unknown theme '$theme_name' (no $theme_file)" >&2
    exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
    echo "island: jq is required (dnf install jq)" >&2
    exit 1
fi

mkdir -p "$STATE_DIR" "$CACHE_DIR" "$CACHE_DIR/tmp"

# Preserve existing metrics (barHeight/fontSize) if the state file exists --
# theme changes must never touch metrics. See ARCHITECTURE.md section 4.
bar_height=37
font_size=15
if [[ -f "$STATE_FILE" ]]; then
    bar_height="$(jq -r '.barHeight // 37' "$STATE_FILE")"
    font_size="$(jq -r '.fontSize // 15' "$STATE_FILE")"
fi

state_tmp="$(mktemp "$CACHE_DIR/tmp/island-state.XXXXXXXXXX")"
jq -n --arg active "$theme_name" --argjson barHeight "$bar_height" --argjson fontSize "$font_size" \
    '{active: $active, barHeight: $barHeight, fontSize: $fontSize}' > "$state_tmp"
mv "$state_tmp" "$STATE_FILE"

# hyprlock is a cold process launched independently by hypridle -- it cannot
# read a running QML singleton, so colors are handed off via a plain file.
# Metrics deliberately do NOT flow here (confirmed: lock screen keeps its
# own fixed typography regardless of Island's bar-height/font-size sliders).
bg="$(jq -r '.colors.bg' "$theme_file")"
surface="$(jq -r '.colors.surface' "$theme_file")"
text="$(jq -r '.colors.text' "$theme_file")"
accent="$(jq -r '.colors.accent' "$theme_file")"
danger="$(jq -r '.colors.danger' "$theme_file")"

strip_hash() { echo "${1#\#}" | tr '[:lower:]' '[:upper:]'; }

{
    echo "# generated by island-set-theme.sh -- do not edit by hand"
    echo "# source theme: $theme_name"
    echo "\$island_bg = rgb($(strip_hash "$bg"))"
    echo "\$island_surface = rgb($(strip_hash "$surface"))"
    echo "\$island_text = rgb($(strip_hash "$text"))"
    echo "\$island_accent = rgb($(strip_hash "$accent"))"
    echo "\$island_danger = rgb($(strip_hash "$danger"))"
} > "$HYPRLOCK_COLORS"

echo "island: theme set to '$theme_name', hyprlock colors synced"
