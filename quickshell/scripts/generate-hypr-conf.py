#!/usr/bin/env python3
"""Write Hyprland overrides from the Quickshell settings store.

The generated file lives outside the checkout, under
$XDG_STATE_HOME/quickshell/hypr.lua, and is loaded last by hyprland.lua so
settings win over the hand-written defaults. Values are validated here so a
corrupt settings file can only produce a sane config, never arbitrary Lua.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib import load_settings, state_home  # noqa: E402

CONF = state_home() / "quickshell" / "hypr.lua"

DEFAULTS = {
    "gapsIn": 5,
    "gapsOut": 10,
    "borderSize": 2,
    "rounding": 10,
    "activeOpacity": 1.0,
    "inactiveOpacity": 1.0,
    "dimInactive": True,
    "dimStrength": 0.25,
    "shadowEnabled": True,
    "shadowRange": 4,
    "blurEnabled": True,
    "blurSize": 7,
    "blurPasses": 2,
    "animationsEnabled": True,
    "kbLayout": "us",
    "kbVariant": "",
    "repeatRate": 25,
    "repeatDelay": 600,
    "numlock": True,
    "sensitivity": 0.0,
    "accelProfile": "adaptive",
    "naturalScroll": False,
    "tapToClick": True,
    "disableWhileTyping": True,
    "scrollMethod": "two_finger",
    "monitors": {},
    "autostart": [],
}


def number(settings: dict, key: str, lo: float, hi: float) -> float:
    try:
        value = float(settings.get(key, DEFAULTS[key]))
    except (TypeError, ValueError):
        value = float(DEFAULTS[key])
    return max(lo, min(hi, value))


def integer(settings: dict, key: str, lo: int, hi: int) -> int:
    return int(round(number(settings, key, lo, hi)))


def flag(settings: dict, key: str) -> bool:
    return bool(settings.get(key, DEFAULTS[key]))


def text(settings: dict, key: str, fallback: str) -> str:
    value = settings.get(key, DEFAULTS[key])
    value = value if isinstance(value, str) else fallback
    return " ".join(value.split())


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_bool(value: bool) -> str:
    return "true" if value else "false"


def lua_number(value: float) -> str:
    return str(int(value)) if value == int(value) else f"{value:.3f}".rstrip("0")


def monitor_rules(settings: dict) -> list[str]:
    raw = settings.get("monitors", {})
    if not isinstance(raw, dict):
        return []
    rules = []
    for name, cfg in sorted(raw.items()):
        if not isinstance(name, str) or not isinstance(cfg, dict):
            continue
        mode = cfg.get("mode", "preferred")
        mode = mode if isinstance(mode, str) and mode else "preferred"
        try:
            scale = max(0.5, min(4.0, float(cfg.get("scale", 1.0))))
        except (TypeError, ValueError):
            scale = 1.0
        try:
            transform = max(0, min(7, int(cfg.get("transform", 0))))
        except (TypeError, ValueError):
            transform = 0
        position = cfg.get("position", "auto")
        position = position if isinstance(position, str) and position else "auto"
        rules.append(
            "hl.monitor({ output = {name}, mode = {mode}, position = {pos}, "
            "scale = {scale}, transform = {transform} })".format(
                name=quote(name),
                mode=quote(mode),
                pos=quote(position),
                scale=lua_number(scale),
                transform=transform,
            )
        )
    return rules


def autostart_commands(settings: dict) -> list[str]:
    raw = settings.get("autostart", [])
    if not isinstance(raw, list):
        return []
    commands = []
    for item in raw:
        if isinstance(item, str):
            command = " ".join(item.split())
            if command and command not in commands:
                commands.append(command)
    return commands


def render(settings: dict) -> str:
    lines = [
        "-- Generated by quickshell/scripts/generate-hypr-conf.py.",
        "-- Edit settings in the desktop settings app; this file is replaced.",
        "hl.config({",
        "    general = {",
        f"        gaps_in = {integer(settings, 'gapsIn', 0, 200)},",
        f"        gaps_out = {integer(settings, 'gapsOut', 0, 200)},",
        f"        border_size = {integer(settings, 'borderSize', 0, 20)},",
        "    },",
        "    input = {",
        f"        kb_layout = {quote(text(settings, 'kbLayout', 'us'))},",
        f"        kb_variant = {quote(text(settings, 'kbVariant', ''))},",
        f"        repeat_rate = {integer(settings, 'repeatRate', 1, 200)},",
        f"        repeat_delay = {integer(settings, 'repeatDelay', 50, 2000)},",
        f"        numlock_by_default = {lua_bool(flag(settings, 'numlock'))},",
        f"        sensitivity = {lua_number(number(settings, 'sensitivity', -1, 1))},",
        f"        accel_profile = {quote(text(settings, 'accelProfile', 'adaptive'))},",
        f"        natural_scroll = {lua_bool(flag(settings, 'naturalScroll'))},",
        f"        [\"tap-to-click\"] = {lua_bool(flag(settings, 'tapToClick'))},",
        f"        disable_while_typing = {lua_bool(flag(settings, 'disableWhileTyping'))},",
        f"        scroll_method = {quote(text(settings, 'scrollMethod', 'two_finger'))},",
        "    },",
        "    decoration = {",
        f"        rounding = {integer(settings, 'rounding', 0, 40)},",
        f"        active_opacity = {lua_number(number(settings, 'activeOpacity', 0.3, 1))},",
        f"        inactive_opacity = {lua_number(number(settings, 'inactiveOpacity', 0.3, 1))},",
        f"        dim_inactive = {lua_bool(flag(settings, 'dimInactive'))},",
        f"        dim_strength = {lua_number(number(settings, 'dimStrength', 0, 1))},",
        "        shadow = {",
        f"            enabled = {lua_bool(flag(settings, 'shadowEnabled'))},",
        f"            range = {integer(settings, 'shadowRange', 0, 60)},",
        "        },",
        "        blur = {",
        f"            enabled = {lua_bool(flag(settings, 'blurEnabled'))},",
        f"            size = {integer(settings, 'blurSize', 1, 20)},",
        f"            passes = {integer(settings, 'blurPasses', 1, 5)},",
        "        },",
        "    },",
        "    animations = {",
        f"        enabled = {lua_bool(flag(settings, 'animationsEnabled'))},",
        "    },",
        "})",
    ]

    rules = monitor_rules(settings)
    if rules:
        lines.append("")
        lines.extend(rules)

    commands = autostart_commands(settings)
    if commands:
        lines.extend(["", 'hl.on("hyprland.start", function()'])
        lines.extend(f"    hl.exec_cmd({quote(command)})" for command in commands)
        lines.append("end)")

    return "\n".join(lines) + "\n"


def main() -> int:
    settings = load_settings()
    CONF.parent.mkdir(parents=True, exist_ok=True)
    tmp = CONF.with_suffix(".lua.tmp")
    tmp.write_text(render(settings))
    tmp.replace(CONF)
    print(f"hypr: wrote {CONF}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
